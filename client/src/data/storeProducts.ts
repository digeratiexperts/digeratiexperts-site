export const getProductsByCategory = (category: ProductCategory): StoreProduct[] => {
  return storeProducts.filter(p => p.category === category).sort((a, b) => a.sortOrder - b.sortOrder);
};

export const getCheckoutEnabledProducts = (): StoreProduct[] => {
  return storeProducts.filter(p => p.isCheckoutEnabled && !p.isContractOnly);
};

export const getContractOnlyProducts = (): StoreProduct[] => {
  return storeProducts.filter(p => p.isContractOnly);
};

export const getManagedClientProducts = (): StoreProduct[] => {
  return storeProducts.filter(p => p.isContractOnly || p.requiredClientType === "managed");
};

export const getCoManagedClientProducts = (): StoreProduct[] => {
  return storeProducts.filter(p => p.requiredClientType === "comanaged" || p.requiredClientType === "public");
};

export const getPublicProducts = (): StoreProduct[] => {
  return storeProducts.filter(p => p.requiredClientType === "public" && !p.isClientOnly);
};

const PRICE_UNIT_BY_TYPE: Record<PricingType, string | null> = {
  monthly: "month",
  yearly: "year",
  per_hour: "hour",
  per_user: "user / month",
  per_seat: "user / month",
  per_endpoint: "endpoint / month",
  per_device: "device",
  per_location: "location / month",
  one_time: null,
};

/** Owns the entire public price string. Do not append `per {unit}` beside this. */
/**
 * A price the client cannot resolve — missing, non-finite, or zero — is never
 * rendered as a currency amount. Zero is a legitimate monetary value, so it
 * cannot double as "unknown"; the fail-closed rule (DE source-of-truth
 * contract, ECO-002) is that an unresolved price reads as a quote state.
 */
export const isResolvedPrice = (value: unknown): value is number =>
  typeof value === "number" && Number.isFinite(value) && value > 0;

export const formatPrice = (product: StoreProduct, unitPrice = product.basePrice): string => {
  if (product.isContractOnly && !isResolvedPrice(product.basePrice)) {
    return "Contact for Quote";
  }
  if (!isResolvedPrice(unitPrice)) {
    return "Contact for Quote";
  }

  const money = `$${unitPrice.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  if (product.pricingType === "per_device" && product.pricingUnit && product.pricingUnit !== "device") {
    return `${money} / ${product.pricingUnit}`;
  }
  const unit = PRICE_UNIT_BY_TYPE[product.pricingType];
  return unit ? `${money} / ${unit}` : money;
};
